import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const bundledManifest = JSON.parse(readFileSync('BUNDLED_DEPENDENCIES.json', 'utf8'));
const bundledPackages = bundledManifest.packages;
if (!Array.isArray(bundledPackages) || bundledPackages.length === 0) {
  throw new Error('BUNDLED_DEPENDENCIES.json must contain at least one browser dependency.');
}

const report = JSON.parse(
  execFileSync('pnpm', ['licenses', 'list', '--json'], { encoding: 'utf8' })
);
const rows = Object.entries(report)
  .flatMap(([license, packages]) =>
    packages.map((pkg) => ({
      license,
      name: pkg.name,
      versions: pkg.versions.join(', '),
      homepage: pkg.homepage ?? '',
      path: pkg.paths?.[0] ?? ''
    }))
  )
  .sort(
    (left, right) =>
      left.name.localeCompare(right.name) || left.license.localeCompare(right.license)
  );

const lines = [
  '# Third-party dependency licenses',
  '',
  'Generated from the locked dependency graph with `pnpm licenses list --json`.',
  'Run `pnpm licenses:generate` after dependency changes and review the diff before release.',
  '',
  '| Package | Version(s) | License | Project |',
  '| --- | --- | --- | --- |',
  ...rows.map(
    ({ name, versions, license, homepage }) =>
      `| \`${name}\` | ${versions} | ${license} | ${homepage ? `[link](${homepage})` : '—'} |`
  ),
  '',
  'Complete license texts for dependencies bundled into the browser distribution are in',
  '[BUNDLED_LICENSES.md](BUNDLED_LICENSES.md). Dependencies installed separately retain',
  'their license texts in their own packages.',
  'Adapted source and trademark notices that require project-level context are recorded in',
  '[THIRD_PARTY_NOTICES.md](THIRD_PARTY_NOTICES.md).',
  ''
];

writeFileSync('THIRD_PARTY_LICENSES.md', `${lines.join('\n')}\n`);
const bundledLines = [
  '# Bundled dependency license texts',
  '',
  'The following dependency code is bundled into the browser distribution shipped by this package.',
  'This file is generated by `pnpm licenses:generate` from the locked dependency graph.',
  ''
];

for (const packageName of bundledPackages) {
  const row = rows.find(({ name }) => name === packageName);
  if (!row?.path) {
    throw new Error(`Unable to locate bundled dependency ${packageName} in the license report.`);
  }

  const licenseFile = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license'].find((candidate) => {
    try {
      readFileSync(join(row.path, candidate));
      return true;
    } catch {
      return false;
    }
  });
  if (!licenseFile) {
    throw new Error(`Unable to locate a license text for bundled dependency ${packageName}.`);
  }

  const licenseText = readFileSync(join(row.path, licenseFile), 'utf8').trim();
  bundledLines.push(
    `## ${packageName} ${row.versions}`,
    '',
    `Declared license: ${row.license}`,
    '',
    '````text',
    licenseText,
    '````',
    ''
  );
}

writeFileSync('BUNDLED_LICENSES.md', `${bundledLines.join('\n')}\n`);
execFileSync(
  'pnpm',
  ['exec', 'prettier', '--write', 'THIRD_PARTY_LICENSES.md', 'BUNDLED_LICENSES.md'],
  {
    stdio: 'inherit'
  }
);
